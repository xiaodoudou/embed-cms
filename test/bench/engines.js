/**
 * End to end benchmark of the storage engines: the real CMS is started on each engine and driven through its REST API, so the
 * numbers include everything a request goes through (authentication, rights, hooks, unique keys, the store, the answer).
 * Create, read, update, delete, list, find, filter and file upload and download are timed, for one client at a time (the
 * latency of an operation) and for eight at once (what the server holds under load).
 * `stores.js` measures the engines alone, through the key-value interface; `bench.js` measures the CMS on one store.
 * Not part of the test run. Usage:
 *
 *   node --expose-gc test/bench/engines.js [--size 10000] [--engines jsondown,sqlite,leveldb,mongodb,postgres]
 *                                          [--scale 1] [--json out.json] [--markdown out.md]
 *   node test/bench/engines.js --table out.json      (print the table of a saved report again)
 *
 * Every engine runs in a process of its own, so that the memory figures are not mixed. `--scale` multiplies how many times each
 * operation is repeated (0.2 for a quick look, 3 for steadier numbers). MongoDB and PostgreSQL are measured when
 * BENCH_MONGODB_URL (host:port) and BENCH_POSTGRES_URL (host:port, with POSTGRES_USER and POSTGRES_PASSWORD in the environment)
 * are set; each gets a database of its own, dropped afterwards. Every time is milliseconds unless the name says otherwise.
 * The records are generated by a seeded generator, so two runs measure the same store.
 *
 * Disk space is the data folder of the CMS for the local engines (the store and the uploaded files). For the two servers it
 * is what the server holds for the database of the run, plus the uploaded files, which stay in the data folder whatever the
 * engine: MongoDB's storageSize + indexSize from dbStats after an fsync (a checkpoint; before it the figure is the size of
 * the files before the last writes reached them), the sum of pg_total_relation_size over the tables of PostgreSQL (the rows,
 * their TOAST and their indexes, without the catalogs every database carries).
 */
const fs = require('fs')
const os = require('os')
const path = require('path')
const http = require('http')
const crypto = require('crypto')
const { spawn } = require('child_process')
const { performance } = require('perf_hooks')
const { AsyncLocalStorage } = require('async_hooks')

const args = process.argv.slice(2)
const option = (name, fallback) => {
  const index = args.indexOf(`--${name}`)
  return index >= 0 ? args[index + 1] : fallback
}
let SIZE_FROM_REPORT
const SIZE = Number(option('size', '10000'))
const SCALE = Number(option('scale', '1'))
const REMOTE = ['mongodb', 'postgres']
const DEFAULT_ENGINES = ['jsondown', 'sqlite', 'leveldb']
const AUTH = { Authorization: `Basic ${Buffer.from('localAdmin:localAdmin').toString('base64')}` }

const random = (seed) => () => {
  seed |= 0
  seed = seed + 0x6D2B79F5 | 0
  let t = Math.imul(seed ^ seed >>> 15, 1 | seed)
  t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t
  return ((t ^ t >>> 14) >>> 0) / 4294967296
}
const WORDS = ['Alpha', 'Bravo', 'Charlie', 'Delta', 'Echo', 'Foxtrot', 'Golf', 'Hotel', 'India', 'Juliet', 'Kilo', 'Lima', 'Mike', 'November', 'Oscar', 'Papa', 'Quebec', 'Romeo', 'Sierra', 'Tango']
const mb = (bytes) => Math.round(bytes / 1024 / 1024 * 10) / 10
const round = (value, digits = 3) => Math.round(value * 10 ** digits) / 10 ** digits

const dirSize = (dir) => {
  let total = 0
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    total += entry.isDirectory() ? dirSize(full) : fs.statSync(full).size
  }
  return total
}

