const THROUGHPUT = (name) => /_(\d+)_parallel$/.test(name)

/**
 * One engine in a child process; a child that ends without a result (the machine refused the connections to its server
 * for too long) is started again, up to three times, on a fresh database each time.
 */
async function runEngine (engine) {
  for (let attempt = 1; ; attempt++) {
    try {
      return await runEngineOnce(engine)
    } catch (error) {
      if (attempt >= 3) {
        throw error
      }
      console.error(`  ${error.message}: starting ${engine} again`)
    }
  }
}

function runEngineOnce (engine) {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, ['--expose-gc', '--no-deprecation', '--no-warnings', __filename, '--child', engine, '--size', String(SIZE), '--scale', String(SCALE)], { stdio: ['ignore', 'pipe', 'inherit'], env: process.env })
    let output = ''
    child.stdout.on('data', chunk => { output += chunk })
    child.on('close', (code) => {
      const line = output.trim().split('\n').pop()
      try {
        resolve(JSON.parse(line))
      } catch {
        reject(new Error(`${engine} exited with ${code} and no result`))
      }
    })
  })
}

/**
 * The results as a markdown table. Every value carries its unit: milliseconds for the time of one operation, operations per
 * second for the parallel ones, MB for memory and disk. The best of a row is in bold.
 */
function table (results) {
  const engines = results.map(result => result.engine)
  const best = (values, lower) => values.filter(v => v !== undefined).reduce((a, b) => (lower ? Math.min(a, b) : Math.max(a, b)), lower ? Infinity : -Infinity)
  const row = (label, values, lower, format) => {
    const top = best(values, lower)
    // one value in bold: the first of the best, if two are equal
    const winner = values.indexOf(top)
    return `| ${label} | ${values.map((value, i) => value === undefined ? 'N/A' : (i === winner ? `**${format(value)}**` : format(value))).join(' | ')} |`
  }
  const ms = (value) => `${value.toLocaleString('en')} ms`
  const megabytes = (value) => `${value.toLocaleString('en')} MB`
  const perSecond = (value) => `${value.toLocaleString('en')} ops/s`
  const lines = [`| ${(SIZE_FROM_REPORT || SIZE).toLocaleString('en')} records | ${engines.map(e => `\`${e}\``).join(' | ')} |`, `|---|${engines.map(() => '---').join('|')}|`]
  lines.push(row('Starting the server (reopening the store)', results.map(r => r.startMs), true, ms))
  lines.push(row('Memory after loading the records', results.map(r => r.rssAfterSeedMb), true, megabytes))
  lines.push(row('Memory after the operations', results.map(r => r.rssAfterOperationsMb), true, megabytes))
  lines.push(row('Disk space', results.map(r => r.diskMb), true, megabytes))
  for (const name of Object.keys(LABELS)) {
    const values = results.map(r => r.operations && r.operations[name])
    if (THROUGHPUT(name)) {
      lines.push(row(`${LABELS[name]} (higher is better)`, values.map(v => v && v.opsPerSecond), false, perSecond))
    } else {
      lines.push(row(LABELS[name], values.map(v => v && v.ms), true, ms))
    }
  }
  return lines.join('\n')
}

async function main () {
  const requested = option('engines')
  const engines = requested ? requested.split(',') : [...DEFAULT_ENGINES, ...(process.env.BENCH_MONGODB_URL ? ['mongodb'] : []), ...(process.env.BENCH_POSTGRES_URL ? ['postgres'] : [])]
  const results = []
  for (const engine of engines) {
    console.error(`--- ${engine}, ${SIZE} records`)
    const result = await runEngine(engine)
    for (const [name, value] of Object.entries(result.operations || {})) {
      if (value.failures) {
        console.error(`  ${name}: ${value.failures} of ${value.count} requests failed`)
      }
      if (value.connectionRetries) {
        console.error(`  ${name}: ${value.connectionRetries} connections dropped by the machine and tried again (${value.retryMs} ms, kept out of the figures)`)
      }
    }
    results.push(result)
  }
  const report = { node: process.version, cpus: os.cpus().length, platform: `${os.platform()} ${os.release()}`, size: SIZE, scale: SCALE, results }
  if (option('json')) {
    fs.writeFileSync(option('json'), JSON.stringify(report, null, 2))
  }
  const markdown = table(results)
  if (option('markdown')) {
    fs.writeFileSync(option('markdown'), markdown + '\n')
  }
  console.log(markdown)
  process.exit(0)
}

if (option('table')) {
  // print the table of a report written with --json again (after a change of the format)
  const report = JSON.parse(fs.readFileSync(option('table'), 'utf8'))
  SIZE_FROM_REPORT = report.size
  console.log(table(report.results))
} else if (option('child')) {
  runChild(option('child'))
    .then((result) => { process.stdout.write(`${JSON.stringify(result)}\n`); process.exit(0) })
    .catch((error) => { console.error(error); process.exit(1) })
} else {
  main().catch((error) => { console.error(error); process.exit(1) })
}
